assert.throws(()=>parse(''),/input/);
assert.throws(()=>parseToolpath(new ArrayBuffer(8*1024*1024+1)),/8 MiB/);
assert.throws(()=>parse('G1 X1\0'),/NUL/);
assert.throws(()=>parse(';'+ 'a'.repeat(4097)),/line length/);
assert.throws(()=>parse(prefix+'G1 X1 E1\nG1 X2 E2\n',{maxSegments:1}),/segments/);
assert.throws(()=>parse(prefix+'G1 X999999999 E1\n'),/Numeric/);
assert.throws(()=>parse(prefix+'G1 X100001 E1\n'),/Coordinate/);
