// Pure bounded offline parser: no DOM, renderer, sockets or printer.
const assert = require('node:assert/strict');
const {parseToolpath} = require('../finderlab/webstatic/toolpath-worker.js');
const bytes = s => new TextEncoder().encode(s).buffer;
const parse = (s, options) => parseToolpath(bytes(s), options);
const prefix = 'G21\nG90\nM82\nG92 E0\nG1 X0 Y0 Z.2\n';
let r = parse(prefix + 'G1 X10 E1\nG1 E.5\nG1 E1\nG1 Y10 E2\nG1 Z.4\nG1 X0 E3\n');
assert.equal(r.counts.extrusion, 3); assert.equal(r.counts.travel, 1);
assert.deepEqual(r.layers, [.2, .4]);
assert.deepEqual([...r.positions.slice(0,6)], [0,0,Math.fround(.2),10,0,Math.fround(.2)]);
assert.equal(r.counts.unresolved, 1, 'initial unknown origin is not connected to arbitrary zero');
r = parse(prefix + 'G1 X1 E1\nG92 E0\nG1 Y1 E.5\n');
assert.equal(r.counts.extrusion, 2, 'G92 E resets absolute origin');
r = parse(prefix + 'G1 E-1\nG92 E0\nG1 X1 E1\nG1 X2 E2\n');
assert.deepEqual([...r.kinds],[1,0], 'coordinate resets do not erase retract debt');
r = parse('G21\nG90\nM83\nG1 X0 Y0 Z1\nG1 X1 E-1\nG1 X2 E1\nG1 X3 E.5\n');
assert.deepEqual([...r.kinds], [1,1,0], 'retract and restoration are not deposition');
r = parse('G21\nG90\nG1 X0 Y0 Z1\nG1 X1 E1\n');
assert.equal(r.counts.unknown, 1);
assert(r.warnings.some(s => s.includes('Unresolved extrusion')));
r = parse('G21\nG90\nG92 E0\nG1 X0 Y0 Z1\nG1 X1 E1\n', {assumeAbsoluteE:true});
assert.equal(r.counts.extrusion, 1); assert(r.warnings.some(s => s.includes('ASSUMED')));
r = parse(prefix + 'G1 X1 E1\nG28\nG1 X2 E2\nG1 Y1 Z.2\nG92 E0\nG1 X3 E1\n');
assert.equal(r.counts.extrusion, 2); assert(r.counts.unresolved >= 2);
assert(r.warnings.some(s => s.includes('Homing')));
r = parse(prefix + 'G1 X1 E1\nG2 X8 Y8 I1 J1 E2\nG1 X9 E3\n');
assert.equal(r.positions.length,6,'unsupported arcs never become straight chords');
assert(r.counts.unsupported > 0);
r = parse(prefix + 'G1 X1 E1\nG92 X100\nG1 X101 E2\n');
assert.equal(r.counts.extrusion,1,'coordinate reset does not create imaginary frame-crossing moves');
r = parse('G20\nG90\nM82\nG92 E0\nG1 X0 Y0 Z1\nG1 X1 E1\n');
assert(Math.abs(r.positions[3]-25.4)<1e-5);
r = parse(prefix + 'G1 X1 E1\nG91\nM83\nG1 Y1 E1\n');
assert.equal(r.counts.extrusion,2);
const body = new Uint8Array(bytes(prefix + 'G1 X1 E1\n'));
const gx = new Uint8Array(58+body.length);gx.set(new TextEncoder().encode('xgcode 1.0\n\0'));new DataView(gx.buffer).setUint32(20,58,true);gx.set(body,58);
r=parseToolpath(gx.buffer); assert.equal(r.gxOffset,58);assert.equal(r.counts.extrusion,1);
