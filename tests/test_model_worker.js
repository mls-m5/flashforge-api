const assert=require('node:assert/strict');
const {parseModel}=require('../finderlab/webstatic/model-worker.js');
const ascii='solid test\nfacet normal 0 0 1\nouter loop\nvertex 10 20 30\nvertex 11 20 30\nvertex 10 21 30\nendloop\nendfacet\nendsolid test\n';
const bytes=s=>new TextEncoder().encode(s).buffer;
let r=parseModel(bytes(ascii));assert.equal(r.triangles,1);assert.deepEqual(r.dimensions,[1,1,0]);
assert.deepEqual(r.bounds,[[10,11],[20,21],[30,30]]);assert.deepEqual([...r.normals.slice(0,3)],[0,0,1]);
const binary=new ArrayBuffer(134),v=new DataView(binary);v.setUint32(80,1,true);
[0,0,0,1,0,0,0,1,0].forEach((n,i)=>v.setFloat32(96+i*4,n,true));
r=parseModel(binary);assert.equal(r.triangles,1);assert.deepEqual(r.dimensions,[1,1,0]);
v.setFloat32(96,NaN,true);assert.throws(()=>parseModel(binary),/coordinate/);
assert.throws(()=>parseModel(new ArrayBuffer(32*1024*1024+1)),/32 MiB/);
assert.throws(()=>parseModel(bytes(ascii.replace('vertex 11','vertex 100001'))),/coordinate/);
assert.throws(()=>parseModel(bytes(ascii.replace('vertex 11','vertex Infinity'))),/vertex/);
assert.throws(()=>parseModel(bytes(ascii.replace('vertex 11 20 30\n',''))),/triangle/);
assert.throws(()=>parseModel(bytes('solid test\nendsolid test')),/empty/);
assert.throws(()=>parseModel(bytes('PK archive')),/Expected/);
assert.throws(()=>parseModel(bytes(ascii.replace('vertex 11 20','vertex 10 20').replace('vertex 10 21','vertex 10 20'))),/nonzero/);
assert.throws(()=>parseModel(bytes('solid x\n'+ 'a'.repeat(4097))),/line limit/);
console.log('Model worker ASCII/binary geometry, normals, bounds and malformed-input checks passed.');
